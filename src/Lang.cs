    public static bool English=Detect();
    static bool Detect() {
        int choice=0;
        try {
            using(var key=Registry.CurrentUser.OpenSubKey(@"Software\PixiePrivacyPro")) {
                object value=key==null ? null : key.GetValue("Language");
                if(value!=null) choice=Convert.ToInt32(value);
            }
        } catch {}
        if(choice==1) return false;
        if(choice==2) return true;
        // Russian also for Belarusian, Kazakh, Kyrgyz, Tajik, Uzbek, Armenian and Azerbaijani Windows (as the installer).
        string language=CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
        return Array.IndexOf(new[]{"ru","be","kk","ky","tg","uz","hy","az"},language)<0;
    }
    public static string T(string ru) {
        string en;
        return English && ru!=null && En.TryGetValue(ru,out en) ? en : ru;
